#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "lowercase")]
pub enum CampState {
    Up,
    Down,
    Unknown,
}

#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
pub struct CampStatus {
    pub id: String,
    pub side: CampSide,
    pub state: CampState,
    pub down_since: Option<f64>,
    pub respawn_at: Option<f64>,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "lowercase")]
pub enum CampEventKind {
    Cleared,
    Respawned,
    Retracted,
}

#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
pub struct CampEvent {
    pub id: String,
    pub side: CampSide,
    pub at: f64,
    pub kind: CampEventKind,
    /// for 'cleared': expected respawn time (s)
    pub respawn_at: Option<f64>,
    /// for 'cleared': last time the live icon was actually seen.
    pub earliest: Option<f64>,
}

#[derive(Clone, Copy, Debug, PartialEq, Serialize, Deserialize)]
pub struct CampTrackerOptions {
    pub min_frames: u32,
    pub min_sec: f64,
    pub visible_threshold: f64,
}

impl Default for CampTrackerOptions {
    fn default() -> Self {
        CampTrackerOptions { min_frames: 3, min_sec: 1.0, visible_threshold: 0.6 }
    }
}

/// Seconds before respawn at which the grey / yellow hourglass appears.
pub fn grey_lead(c: &CampDef) -> f64 {
    if c.kind == CampKind::Scuttle {
        60.0
    } else {
        30.0
    }
}
pub const YELLOW_LEAD: f64 = 10.0;

#[derive(Clone, Debug)]
struct Track {
    def: CampDef,
    stable: Option<CampIconState>,
    cand: Option<CampIconState>,
    cand_since: f64,
    cand_count: u32,
    cand_visible: bool,
    last_up: Option<f64>,
    state: CampState,
    down_since: Option<f64>,
    respawn_at: Option<f64>,
    pending_confirm: bool,
}

fn fresh_track(def: &CampDef) -> Track {
    Track { def: *def, stable: None, cand: None, cand_since: 0.0, cand_count: 0, cand_visible: false, last_up: None, state: CampState::Unknown, down_since: None, respawn_at: None, pending_confirm: false }
}

/// Turns per-frame camp readings into debounced camp states, clear events and respawn times.
pub struct CampTracker {
    pub events: Vec<CampEvent>,
    tracks: Vec<Track>,
    opts: CampTrackerOptions,
    icons_in_fog: Option<bool>,
    fog_icon_frames: u32,
}

impl Default for CampTracker {
    fn default() -> Self {
        Self::new(CampTrackerOptions::default())
    }
}

impl CampTracker {
    pub fn new(opts: CampTrackerOptions) -> CampTracker {
        CampTracker { events: Vec::new(), tracks: CAMPS.iter().map(fresh_track).collect(), opts, icons_in_fog: None, fog_icon_frames: 0 }
    }

    pub fn reset(&mut self) {
        self.events.clear();
        self.icons_in_fog = None;
        self.fog_icon_frames = 0;
        self.tracks = CAMPS.iter().map(fresh_track).collect();
    }

    /// `visible`: optional P(visible) at normalized minimap coords (e.g. from the fog mask).
    /// Returns the status of every camp; new events are appended to `self.events`.
    pub fn update(&mut self, game_time_sec: f64, readings: &[CampReading], visible: Option<&dyn Fn(f64, f64) -> f64>) -> Vec<CampStatus> {
        let mut fog_icon = false;
        let have_vision = visible.is_some();
        for ti in 0..self.tracks.len() {
            let id = self.tracks[ti].def.id;
            let r = readings.iter().find(|r| r.id == id);
            let def = self.tracks[ti].def;
            let vis = match visible {
                Some(f) => f(def.x, def.y) >= self.opts.visible_threshold,
                None => true,
            };
            if let Some(icon) = r.and_then(|r| r.icon) {
                let accept = {
                    let t = &mut self.tracks[ti];
                    if icon == CampIconState::Up {
                        t.last_up = Some(game_time_sec);
                    }
                    if have_vision && !vis && icon != CampIconState::Empty && def.kind != CampKind::Scuttle {
                        fog_icon = true;
                    }
                    if Some(icon) == t.cand {
                        t.cand_count += 1;
                        t.cand_visible = t.cand_visible && vis;
                    } else {
                        t.cand = Some(icon);
                        t.cand_since = game_time_sec;
                        t.cand_count = 1;
                        t.cand_visible = vis;
                    }
                    t.cand != t.stable && t.cand_count >= self.opts.min_frames && game_time_sec - t.cand_since >= self.opts.min_sec
                };
                if accept {
                    let (cand, since, cv) = {
                        let t = &self.tracks[ti];
                        (t.cand.unwrap(), t.cand_since, t.cand_visible)
                    };
                    self.accept(ti, cand, since, cv, have_vision);
                }
            }
            self.expire(ti, game_time_sec);
        }
        if have_vision && self.icons_in_fog.is_none() {
            self.fog_icon_frames = if fog_icon { self.fog_icon_frames + 1 } else { 0 };
            if self.fog_icon_frames >= 3 {
                self.icons_in_fog = Some(true);
            }
        }
        self.status()
    }

    pub fn status(&self) -> Vec<CampStatus> {
        self.tracks.iter().map(|t| CampStatus { id: t.def.id.to_string(), side: t.def.side, state: t.state, down_since: t.down_since, respawn_at: t.respawn_at }).collect()
    }

    fn accept(&mut self, ti: usize, icon: CampIconState, since: f64, visible_throughout: bool, have_vision: bool) {
        let icons_in_fog = self.icons_in_fog;
        let t = &mut self.tracks[ti];
        let prev = t.stable;
        let c = t.def;
        t.stable = Some(icon);
        match icon {
            CampIconState::Up => {
                if t.state == CampState::Down {
                    self.events.push(CampEvent { id: c.id.into(), side: c.side, at: since, kind: CampEventKind::Respawned, respawn_at: None, earliest: None });
                }
                t.state = CampState::Up;
                t.down_since = None;
                t.respawn_at = None;
                t.pending_confirm = false;
            }
            CampIconState::Respawning | CampIconState::RespawnSoon => {
                let at = since + if icon == CampIconState::Respawning { grey_lead(&c) } else { YELLOW_LEAD };
                let pinned = prev.is_some();
                if pinned || t.respawn_at.is_none() || t.pending_confirm {
                    t.respawn_at = Some(at);
                }
                if c.kind != CampKind::Scuttle && (t.down_since.is_none() || (pinned && icon == CampIconState::Respawning)) {
                    t.down_since = t.respawn_at.map(|r| r - c.respawn_sec);
                }
                t.state = CampState::Down;
                t.pending_confirm = false;
            }
            CampIconState::Empty => {
                if prev == Some(CampIconState::Up) {
                    let trust = if c.kind == CampKind::Scuttle { have_vision && visible_throughout } else { !have_vision || visible_throughout || icons_in_fog == Some(true) };
                    if trust {
                        t.state = CampState::Down;
                        t.down_since = Some(since);
                        t.respawn_at = if c.kind == CampKind::Scuttle { None } else { Some(since + c.respawn_sec) };
                        t.pending_confirm = c.kind != CampKind::Scuttle;
                        let ev = CampEvent { id: c.id.into(), side: c.side, at: since, kind: CampEventKind::Cleared, respawn_at: t.respawn_at, earliest: Some(t.last_up.unwrap_or(since)) };
                        self.events.push(ev);
                    } else {
                        t.state = CampState::Unknown;
                        t.down_since = None;
                        t.respawn_at = None;
                        t.pending_confirm = false;
                    }
                } else if prev.is_none() {
                    t.state = CampState::Unknown;
                }
            }
        }
    }

    /// A cleared camp must show its hourglass on schedule; if it doesn't, retract the clear.
    fn expire(&mut self, ti: usize, now: f64) {
        let t = &mut self.tracks[ti];
        let Some(respawn_at) = t.respawn_at else { return };
        if t.state != CampState::Down {
            return;
        }
        if t.pending_confirm && t.stable == Some(CampIconState::Empty) && now > respawn_at - grey_lead(&t.def) + 15.0 {
            self.events.push(CampEvent { id: t.def.id.into(), side: t.def.side, at: now, kind: CampEventKind::Retracted, respawn_at: None, earliest: None });
            t.state = CampState::Unknown;
            t.down_since = None;
            t.respawn_at = None;
            t.pending_confirm = false;
        } else if !t.pending_confirm && now > respawn_at + 20.0 && t.stable != Some(CampIconState::Up) {
            t.state = CampState::Unknown;
            t.down_since = None;
            t.respawn_at = None;
        }
    }
}

pub fn camp_by_id(id: &str) -> Option<&'static CampDef> {
    CAMPS.iter().find(|c| c.id == id)
}
